# ROW — sqlite3.Row taqlidi (int index VA kalit bo'yicha)
# ============================================================
class _Row:
    __slots__ = ("_vals", "_cols")

    def __init__(self, vals, cols):
        self._vals = vals
        self._cols = cols  # {colname: index}

    def __getitem__(self, key):
        if isinstance(key, int):
            return self._vals[key]
        if isinstance(key, slice):
            return self._vals[key]
        return self._vals[self._cols[key]]

    def __iter__(self):
        return iter(self._vals)

    def __len__(self):
        return len(self._vals)

    def keys(self):
        return list(self._cols.keys())

    def __contains__(self, key):
        return key in self._cols

    def get(self, key, default=None):
        idx = self._cols.get(key)
        return self._vals[idx] if idx is not None else default


