# CURSOR
# ============================================================
class PgCursor:
    def __init__(self, conn):
        self._conn = conn
        self._cur = conn._pg.cursor()
        self._buf = []
        self._idx = 0
        self._cols_map = {}   # ustun-nomlari -> index (RELEASE'dan oldin saqlanadi)
        self.lastrowid = None
        self.rowcount = -1

    def _cols(self):
        # RELEASE/commit'dan keyin self._cur.description None bo'ladi — shuning uchun
        # execute paytida saqlangan ustun xaritasini qaytaramiz (audit #1 fix).
        return self._cols_map

    def execute(self, sql, params=None):
        params = tuple(params) if params else ()

        # PRAGMA -> no-op
        if re.match(r"^\s*PRAGMA\b", sql, re.I):
            self._buf, self._idx, self.lastrowid, self.rowcount = [], 0, None, -1
            self._cols_map = {}
            return self

        translated = translate_sql(sql)
        is_insert = bool(_RE_IS_INSERT.match(translated))
        has_returning = " RETURNING " in (" " + translated.upper() + " ")
        is_ddl = bool(_RE_IS_DDL.match(translated))

        sp = self._conn._next_savepoint()
        self._cur.execute(f"SAVEPOINT {sp}")
        try:
            if is_insert and not has_returning:
                # lastrowid uchun RETURNING id — id ustuni bo'lmasa fallback
                try:
                    self._cur.execute(translated + " RETURNING id", params)
                except Exception:
                    self._cur.execute(f"ROLLBACK TO SAVEPOINT {sp}")
                    self._cur.execute(translated, params)
            else:
                self._cur.execute(translated, params)
            # MUHIM (audit #1 fix): natija + ustun-nomlarni RELEASE'dan OLDIN o'qiymiz.
            # RELEASE SAVEPOINT o'sha cursor'da bajarilsa, psycopg cursor.description'ni
            # None qiladi va natija to'plami yo'qoladi — shu sabab BARCHA SELECT bo'sh
            # qaytar edi. Buferlash endi RELEASE'dan oldin.
            self.rowcount = self._cur.rowcount
            if self._cur.description is not None:
                self._cols_map = {d.name: i for i, d in enumerate(self._cur.description)}
                captured = self._cur.fetchall()
            else:
                self._cols_map = {}
                captured = []
            self._cur.execute(f"RELEASE SAVEPOINT {sp}")
        except Exception:
            try:
                self._cur.execute(f"ROLLBACK TO SAVEPOINT {sp}")
                self._cur.execute(f"RELEASE SAVEPOINT {sp}")
            except Exception:
                pass
            raise

        self._idx = 0
        if is_insert and not has_returning:
            # RETURNING id natijasi -> lastrowid
            self.lastrowid = captured[0][0] if captured else None
            self._buf = []
        else:
            self._buf = captured

        if is_insert or is_ddl or re.match(r"^\s*(UPDATE|DELETE)\b", translated, re.I):
            self._conn._dirty = True
        else:
            # faqat o'qish bo'lsa va yozilmagan o'zgarish yo'q bo'lsa — snapshotni bo'shatamiz
            self._conn._maybe_autocommit_read()
        return self

    def executemany(self, sql, seq_of_params):
        translated = translate_sql(sql)
        sp = self._conn._next_savepoint()
        self._cur.execute(f"SAVEPOINT {sp}")
        try:
            self._cur.executemany(translated, [tuple(p) for p in seq_of_params])
            self._cur.execute(f"RELEASE SAVEPOINT {sp}")
        except Exception:
            try:
                self._cur.execute(f"ROLLBACK TO SAVEPOINT {sp}")
                self._cur.execute(f"RELEASE SAVEPOINT {sp}")
            except Exception:
                pass
            raise
        self.rowcount = self._cur.rowcount
        self.lastrowid = None
        self._buf, self._idx, self._cols_map = [], 0, {}
        self._conn._dirty = True
        return self

    def _wrap(self, row):
        if row is None:
            return None
        return _Row(list(row), self._cols())

    def fetchone(self):
        if self._idx >= len(self._buf):
            return None
        row = self._buf[self._idx]
        self._idx += 1
        return self._wrap(row)

    def fetchall(self):
        rows = self._buf[self._idx:]
        self._idx = len(self._buf)
        cols = self._cols()
        return [_Row(list(r), cols) for r in rows]

    def fetchmany(self, size=1):
        rows = self._buf[self._idx:self._idx + size]
        self._idx += len(rows)
        cols = self._cols()
        return [_Row(list(r), cols) for r in rows]

    def __iter__(self):
        return iter(self.fetchall())

    def close(self):
        try:
            self._cur.close()
        except Exception:
            pass


# ============================================================
# CONNECTION
# ============================================================
class PgConnection:
    def __init__(self, pg_conn):
        self._pg = pg_conn
        self._pg.autocommit = False
        self._dirty = False
        self._sp_counter = 0
        self.row_factory = None  # sqlite3.Row uchun no-op (shim o'zi _Row qaytaradi)

    def _next_savepoint(self):
        self._sp_counter += 1
        return f"_sp{self._sp_counter}"

    def _maybe_autocommit_read(self):
        """Faqat o'qishdan keyin, yozilmagan o'zgarish yo'q bo'lsa — tranzaksiyani
        yopamiz (idle-in-transaction va eskirgan snapshotning oldini olish)."""
        if not self._dirty:
            try:
                self._pg.commit()
            except Exception:
                pass

    def cursor(self):
        return PgCursor(self)

    def execute(self, sql, params=None):
        cur = self.cursor()
        cur.execute(sql, params)
        return cur

    def commit(self):
        self._pg.commit()
        self._dirty = False

    def rollback(self):
        self._pg.rollback()
        self._dirty = False

    def close(self):
        try:
            self._pg.close()
        except Exception:
            pass


def connect(dsn: str) -> PgConnection:
    import psycopg
    return PgConnection(psycopg.connect(dsn))
