"""
PostgreSQL moslashtiruvchi qatlam (shim) — Faza 0.

Maqsad: `database.py` dagi ~89 ta sqlite3 so'rovini O'ZGARTIRMASDAN PostgreSQL'da
ishlatish. Shim sqlite3.Connection/Cursor API'sini taqlid qiladi, lekin ostida
psycopg (PostgreSQL) bilan gaplashadi.

Asosiy ish:
  - `?`            -> `%s`                (placeholder)
  - `CURRENT_TIMESTAMP` -> to_char(now()...)  (TEXT-timestamp parity, 'YYYY-MM-DD HH:MM:SS')
  - `INSERT OR IGNORE` -> `INSERT ... ON CONFLICT DO NOTHING`
  - `INSERT OR REPLACE` -> `INSERT ... ON CONFLICT DO NOTHING`  (best-effort; kodda hozir ishlatilmaydi)
  - `cursor.lastrowid` -> INSERT'ga `RETURNING id` qo'shib ushlaymiz (app_meta uchun fallback)
  - DDL: `INTEGER PRIMARY KEY AUTOINCREMENT` -> IDENTITY; INTEGER->BIGINT, REAL->DOUBLE
    PRECISION, BOOLEAN->SMALLINT, TIMESTAMP->TEXT
  - `strftime('%H'/'%w', x)` -> EXTRACT(HOUR/DOW ...)   (analitika)
  - `PRAGMA ...` -> no-op
  - Natija qatorlari sqlite3.Row kabi: row[0] HAM row['col'] HAM dict(row) ishlaydi.

MUHIM (tranzaksiya): har bir execute SAVEPOINT ichida bajariladi — ushlangan xato
(try/except) butun tranzaksiyani buzmasin (SQLite "forgiveness" emulatsiyasi). Bu
`init_db` dagi try/except ALTER naqshi uchun zarur.

Bu modul faqat DB_BACKEND=postgres bo'lganda import qilinadi.
"""
import re
import logging

# TIMESTAMP ustunlari uchun: SQLite CURRENT_TIMESTAMP -> 'YYYY-MM-DD HH:MM:SS' (UTC).
# PG'da aynan shu formatni beradigan ifoda (parity uchun TEXT ustunga yoziladi):
PG_NOW_TEXT = "to_char((now() AT TIME ZONE 'UTC'), 'YYYY-MM-DD HH24:MI:SS')"


# ============================================================
# SQL TARJIMA (sof funksiya — PG'siz test qilinadi)
# ============================================================
def _split_literals(sql: str):
    """SQL'ni ['string-literal' | oddiy-matn] bo'laklarga ajratadi.
    Qaytaradi: [(is_string, text), ...]. '' (qo'sh apostrof) escape hisobga olinadi."""
    out, buf, i, n = [], [], 0, len(sql)
    while i < n:
        ch = sql[i]
        if ch == "'":
            if buf:
                out.append((False, "".join(buf)))
                buf = []
            s = ["'"]
            i += 1
            while i < n:
                if sql[i] == "'":
                    if i + 1 < n and sql[i + 1] == "'":
                        s.append("''")
                        i += 2
                        continue
                    s.append("'")
                    i += 1
                    break
                s.append(sql[i])
                i += 1
            out.append((True, "".join(s)))
        else:
            buf.append(ch)
            i += 1
    if buf:
        out.append((False, "".join(buf)))
    return out


def _apply_outside_strings(sql: str, fn) -> str:
    """fn ni faqat string-literal bo'lmagan bo'laklarga qo'llaydi."""
    return "".join(seg if is_str else fn(seg) for is_str, seg in _split_literals(sql))


# DDL tip almashtirishlari (faqat CREATE/ALTER uchun, katta harfli tip so'zlari)
_DDL_TYPE_SUBS = [
    (re.compile(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", re.I),
     "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"),
    (re.compile(r"\bAUTOINCREMENT\b", re.I), ""),
    (re.compile(r"\bINTEGER\b", re.I), "BIGINT"),
    (re.compile(r"\bREAL\b", re.I), "DOUBLE PRECISION"),
    (re.compile(r"\bBOOLEAN\b", re.I), "SMALLINT"),
    (re.compile(r"\bTIMESTAMP\b", re.I), "TEXT"),
]

_RE_STRFTIME_H = re.compile(r"strftime\(\s*'%H'\s*,\s*([^)]+?)\s*\)", re.I)
_RE_STRFTIME_W = re.compile(r"strftime\(\s*'%w'\s*,\s*([^)]+?)\s*\)", re.I)
# SQLite datetime('now', '-7 days') -> PG to_char(now()...-interval, 'YYYY-MM-DD HH24:MI:SS')
# (created_at TEXT bilan string-solishtirish uchun aynan shu format).
_RE_DATETIME_NOW = re.compile(
    r"datetime\(\s*'now'\s*(?:,\s*'\s*([+-]?)\s*(\d+)\s+(\w+)\s*'\s*)?\)", re.I
)


def _datetime_now_repl(m):
    sign, num, unit = m.group(1), m.group(2), m.group(3)
    if num is None:
        expr = "(now() AT TIME ZONE 'UTC')"
    else:
        op = "-" if sign == "-" else "+"
        expr = f"(now() AT TIME ZONE 'UTC' {op} interval '{num} {unit}')"
    return f"to_char({expr}, 'YYYY-MM-DD HH24:MI:SS')"
_RE_CURRENT_TS = re.compile(r"\bCURRENT_TIMESTAMP\b", re.I)
_RE_INSERT_IGNORE = re.compile(r"^\s*INSERT\s+OR\s+IGNORE\s+INTO\b", re.I)
_RE_INSERT_REPLACE = re.compile(r"^\s*INSERT\s+OR\s+REPLACE\s+INTO\b", re.I)
_RE_IS_INSERT = re.compile(r"^\s*INSERT\s+INTO\b", re.I)
_RE_IS_DDL = re.compile(r"^\s*(CREATE|ALTER|DROP)\b", re.I)


def translate_sql(sql: str) -> str:
    """sqlite3 so'rovini PostgreSQL so'roviga aylantiradi. Sof string->string."""
    # 1) strftime (SQL ichidagi literal % ni ham olib tashlaydi)
    sql = _RE_STRFTIME_H.sub(r"CAST(EXTRACT(HOUR FROM (\1)::timestamp) AS INTEGER)", sql)
    sql = _RE_STRFTIME_W.sub(r"CAST(EXTRACT(DOW FROM (\1)::timestamp) AS INTEGER)", sql)
    # 1b) datetime('now', '-N days')
    sql = _RE_DATETIME_NOW.sub(_datetime_now_repl, sql)

    # 2) DDL tip almashtirishlari
    if _RE_IS_DDL.match(sql):
        for rx, repl in _DDL_TYPE_SUBS:
            sql = rx.sub(repl, sql)

    # 3) CURRENT_TIMESTAMP -> to_char(...)  (string literal ichida emas)
    sql = _apply_outside_strings(sql, lambda s: _RE_CURRENT_TS.sub(PG_NOW_TEXT, s))

    # 4) INSERT OR IGNORE / REPLACE
    on_conflict = False
    if _RE_INSERT_IGNORE.match(sql):
        sql = _RE_INSERT_IGNORE.sub(lambda m: m.group(0).replace("OR IGNORE", "").replace("or ignore", ""), sql, count=1)
        sql = re.sub(r"^\s*INSERT\s+INTO\b", "INSERT INTO", sql, count=1, flags=re.I)
        on_conflict = True
    elif _RE_INSERT_REPLACE.match(sql):
        # Best-effort: konflikt ustunlarini bilmaganimiz uchun DO NOTHING.
        sql = re.sub(r"^\s*INSERT\s+OR\s+REPLACE\s+INTO\b", "INSERT INTO", sql, count=1, flags=re.I)
        on_conflict = True

    # 5) literal % -> %% (psycopg talabi). %s hali yo'q, shuning uchun xavfsiz.
    sql = sql.replace("%", "%%")

    # 6) ? -> %s  (string literal ichida emas)
    sql = _apply_outside_strings(sql, lambda s: s.replace("?", "%s"))

    if on_conflict:
        sql = sql.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    return sql


